import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createInterface} from 'node:readline';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fixture=spawn(process.env.PYTHON || 'python3',['tests/fixtures/phone_server.py'],{stdio:['pipe','pipe','inherit']});
const pending=[],lines=[];
const reader=createInterface({input:fixture.stdout});
reader.on('line',line=>{const value=JSON.parse(line);if(pending.length)pending.shift()(value);else lines.push(value);});
const next=()=>lines.length ? Promise.resolve(lines.shift()) : new Promise(resolve=>pending.push(resolve));
const command=async value=>{fixture.stdin.write(value+'\n');return next();};
const initial=await next();
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
try {
  await page.goto(initial.pairingURL);
  await page.getByText('等待 Mac 确认',{exact:true}).waitFor();
  assert.equal(new URL(page.url()).hash,'');
  assert.equal(await page.getByRole('button',{name:'应用位置',exact:true}).isDisabled(),true);
  await command('approve');
  await page.getByText('配对授权已确认。可将此页面添加到主屏幕。',{exact:true}).waitFor();
  const cookies=await page.context().cookies();
  const grant=cookies.find(cookie=>cookie.name==='loc2_control');
  assert.equal(grant.httpOnly,true);assert.equal(grant.sameSite,'Strict');
  await page.getByLabel('WGS84 纬度').fill('1');
  await page.getByLabel('WGS84 经度').fill('2');
  await page.getByLabel('收藏名称').fill('家');
  await page.getByRole('button',{name:'收藏当前草稿',exact:true}).click();
  await page.getByRole('button',{name:'选择 家',exact:true}).waitFor();
  assert.equal((await command('snapshot')).status.target,null);
  await page.getByLabel('WGS84 纬度').fill('3');
  await page.getByLabel('WGS84 经度').fill('4');
  await page.getByRole('button',{name:'应用位置',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#accepted').textContent.includes('3, 4'));
  await page.getByRole('button',{name:'选择 家',exact:true}).click();
  assert.equal(await page.getByLabel('WGS84 纬度').inputValue(),'1');
  assert.equal((await command('snapshot')).status.target.latitude,3);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'/tmp/loc2-favorites.png',fullPage:true});
  await page.getByRole('button',{name:'应用位置',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#accepted').textContent.includes('1, 2'));
  await page.reload();
  await page.getByRole('button',{name:'选择 家',exact:true}).waitFor();
  await page.getByRole('button',{name:'删除 家',exact:true}).click();
  await page.getByText('还没有常用点。',{exact:true}).waitFor();
  await page.getByRole('button',{name:'停止报点',exact:true}).click();
  console.log('PASS authenticated favorite save → select draft only → explicit apply → reload → remove');
} finally {
  await browser.close();fixture.stdin.write('quit\n');fixture.stdin.end();reader.close();
  await new Promise(resolve=>fixture.once('exit',resolve));
}
